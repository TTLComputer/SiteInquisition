#!/usr/bin/env node
// Write THIRD_PARTY_NOTICES.md from the license files of what the release ships:
// the libraries bundled into the UI, the fonts, and Electron. Chromium's own
// notices ship as LICENSES.chromium.html next to the binary.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const fromUi = createRequire(join(root, 'packages/ui/package.json'));
const fromApp = createRequire(join(root, 'packages/app/package.json'));

const SHIPPED = [
  ['react', fromUi, 'UI'],
  ['react-dom', fromUi, 'UI'],
  ['scheduler', createRequire(fromUi.resolve('react-dom/package.json')), 'UI (used by react-dom)'],
  ['@fontsource/inter', fromUi, 'UI font (Inter, SIL Open Font License 1.1)'],
  ['@fontsource/jetbrains-mono', fromUi, 'UI font (JetBrains Mono, SIL Open Font License 1.1)'],
  ['electron', fromApp, 'application runtime; Chromium notices are in LICENSES.chromium.html'],
];

const parts = [
  '# Third-party notices',
  '',
  'SiteInquisition is MIT licensed (see LICENSE). The release includes the software below, each under its own license.',
  'This file is generated by `node scripts/notices.mjs`; do not edit it by hand.',
  '',
];
for (const [name, req, use] of SHIPPED) {
  const dir = dirname(req.resolve(`${name}/package.json`));
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const text = readFileSync(join(dir, 'LICENSE'), 'utf8').trim();
  parts.push(`## ${name} ${pkg.version}`, '', `Used for: ${use}. License: ${pkg.license}.`, '', '```', text, '```', '');
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), parts.join('\n'));
console.log('wrote THIRD_PARTY_NOTICES.md');
